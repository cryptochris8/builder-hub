/** path.join stand-in for win32 (src/shared may not import node:path): backslashes,
 *  both separators accepted, `.` dropped, `..` resolved (the drive is kept). */
const winJoin = (...parts: string[]): string => {
  const segs: string[] = []
  for (const raw of parts.join('\\').split(/[\\/]+/)) {
    if (!raw || raw === '.') continue
    if (raw === '..') {
      if (segs.length > 1) segs.pop()
      continue
    }
    segs.push(raw)
  }
  return segs.join('\\')
}

