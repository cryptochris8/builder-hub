describe('mergeSeed', () => {
  const seeded = (): CreatorStackEntry[] =>
    seedEntries(HOME, () => true, [proj({ id: 'inc', path: 'C:\\Users\\chris\\income-kit' })], LATER, winJoin)

  it('appends every seed the stack lacks, bumps updatedAt and returns a new object', () => {
    const before = emptyStack(NOW)
    const after = mergeSeed(before, seeded(), LATER)
    expect(after).not.toBe(before)
    expect(before.entries).toEqual([])
    expect(after.entries.map((e) => e.id)).toEqual(SEED_CREATOR_STACK.map((s) => s.id))
    expect(after.updatedAt).toBe(LATER)
    expect(after.version).toBe(1)
  })
  it('is idempotent on a second run apart from the timestamps', () => {
    const once = mergeSeed(emptyStack(NOW), seeded(), NOW)
    const twice = mergeSeed(once, seeded(), LATER)
    expect(twice.entries.length).toBe(once.entries.length)
    expect(twice.entries.map((e) => ({ ...e, indexedAt: 0 }))).toEqual(
      once.entries.map((e) => ({ ...e, indexedAt: 0 }))
    )
  })
  it('preserves user edits on a seed-sourced entry and refreshes only exists/projectId/indexedAt', () => {
    const edited = entry({
      id: 'income-kit',
      name: 'My renamed kit',
      aliases: ['my kit'],
      path: 'C:\\Users\\chris\\income-kit',
      capabilities: [cap({ id: 'only-one', usageNotes: 'my notes' })],
      docs: ['MY-NOTES.md'],
      tags: ['mine'],
      exists: false,
      projectId: 'stale',
      indexedAt: 1,
      source: 'seed'
    })
    const after = mergeSeed({ version: 1, entries: [edited], updatedAt: NOW }, seeded(), LATER)
    const kit = byId(after, 'income-kit')
    expect(kit.name).toBe('My renamed kit')
    expect(kit.aliases).toEqual(['my kit'])
    expect(kit.capabilities).toEqual([cap({ id: 'only-one', usageNotes: 'my notes' })])
    expect(kit.docs).toEqual(['MY-NOTES.md'])
    expect(kit.tags).toEqual(['mine'])
    expect(kit.path).toBe('C:\\Users\\chris\\income-kit')
    expect(kit.exists).toBe(true)
    expect(kit.projectId).toBe('inc')
    expect(kit.indexedAt).toBe(LATER)
    expect(after.entries.length).toBe(SEED_CREATOR_STACK.length)
  })
  it('adopts the seeded path when the stored path is marked missing', () => {
    const stale = entry({
      id: 'income-kit',
      path: 'C:\\old-place\\income-kit',
      exists: false,
      source: 'seed',
      aliases: ['kept alias']
    })
    const kit = byId(
      mergeSeed({ version: 1, entries: [stale], updatedAt: NOW }, seeded(), LATER),
      'income-kit'
    )
    expect(kit.path).toBe('C:\\Users\\chris\\income-kit')
    expect(kit.exists).toBe(true)
    expect(kit.projectId).toBe('inc')
    expect(kit.aliases).toEqual(['kept alias'])
  })
  it('keeps a stored path that differs but still exists (the user moved the tool)', () => {
    const moved = entry({
      id: 'income-kit',
      path: 'D:\\moved\\income-kit',
      exists: true,
      projectId: 'moved-proj',
      indexedAt: 1,
      source: 'seed'
    })
    const kit = byId(
      mergeSeed({ version: 1, entries: [moved], updatedAt: NOW }, seeded(), LATER),
      'income-kit'
    )
    expect(kit.path).toBe('D:\\moved\\income-kit')
    expect(kit.exists).toBe(true)
    expect(kit.projectId).toBe('moved-proj')
    expect(kit.indexedAt).toBe(LATER)
  })
  it('treats the same path spelled with other separators/case as the same path', () => {
    const spelled = entry({
      id: 'income-kit',
      path: 'c:/users/CHRIS/income-kit/',
      exists: false,
      source: 'seed'
    })
    const kit = byId(
      mergeSeed({ version: 1, entries: [spelled], updatedAt: NOW }, seeded(), LATER),
      'income-kit'
    )
    expect(kit.path).toBe('c:/users/CHRIS/income-kit/')
    expect(kit.exists).toBe(true)
    expect(kit.projectId).toBe('inc')
  })
  it('clears a stale projectId when the seed no longer resolves to a project', () => {
    const stored = entry({
      id: 'tool-stack',
      path: 'C:\\Users\\chris\\TOOL-STACK.md',
      projectId: 'gone',
      kind: 'catalog',
      source: 'seed'
    })
    const after = mergeSeed({ version: 1, entries: [stored], updatedAt: NOW }, seeded(), LATER)
    expect(byId(after, 'tool-stack')).not.toHaveProperty('projectId')
  })
  it('never touches user or discovered entries that share a seed id', () => {
    const user = entry({ id: 'income-kit', path: 'C:\\mine', exists: false, source: 'user', aliases: ['u'] })
    const disc = entry({
      id: 'tool-stack',
      path: 'C:\\found',
      exists: false,
      source: 'discovered',
      kind: 'catalog'
    })
    const after = mergeSeed({ version: 1, entries: [user, disc], updatedAt: NOW }, seeded(), LATER)
    expect(byId(after, 'income-kit')).toEqual(user)
    expect(byId(after, 'tool-stack')).toEqual(disc)
  })
  it('does not mutate the input stack or its entries', () => {
    const stored = entry({ id: 'income-kit', path: 'C:\\old', exists: false, source: 'seed' })
    const before: CreatorStack = { version: 1, entries: [stored], updatedAt: NOW }
    const snapshot = JSON.parse(JSON.stringify(before))
    mergeSeed(before, seeded(), LATER)
    expect(before).toEqual(snapshot)
  })
})

