describe('projectForPath', () => {
  const home = proj({ id: 'home', name: 'Home', path: 'C:\\Users\\chris' })
  const kit = proj({ id: 'kit', name: 'Income Kit', path: 'C:\\Users\\chris\\income-kit' })
  const projects = [home, kit]

  it('picks the LONGEST matching prefix, not the first registered', () => {
    expect(projectForPath('C:\\Users\\chris\\income-kit\\trailer-factory', projects)?.id).toBe('kit')
    expect(projectForPath('C:\\Users\\chris\\income-kit\\trailer-factory', [kit, home])?.id).toBe('kit')
    expect(projectForPath('C:\\Users\\chris\\TOOL-STACK.md', projects)?.id).toBe('home')
  })
  it('is case-insensitive and accepts forward slashes and trailing separators', () => {
    expect(projectForPath('c:/users/CHRIS/income-kit/', projects)?.id).toBe('kit')
    expect(
      projectForPath('C:\\USERS\\chris\\income-kit\\', [
        proj({ id: 'k', path: 'c:/users/chris/income-kit/' })
      ])?.id
    ).toBe('k')
  })
  it('counts an equal path as inside the project', () => {
    expect(projectForPath('C:\\Users\\chris\\income-kit', projects)?.id).toBe('kit')
  })
  it('does not match a sibling that merely shares a string prefix', () => {
    expect(projectForPath('C:\\Users\\chris\\income-kit-old\\x', [kit])).toBeUndefined()
    expect(projectForPath('C:\\Users\\christine\\x', [home])).toBeUndefined()
  })
  it('returns undefined for no projects, an unrelated drive, an empty path or garbage project paths', () => {
    expect(projectForPath('C:\\Users\\chris\\x', [])).toBeUndefined()
    expect(projectForPath('D:\\elsewhere', projects)).toBeUndefined()
    expect(projectForPath('', projects)).toBeUndefined()
    expect(projectForPath('C:\\Users\\chris\\x', [proj({ id: 'blank', path: '' })])).toBeUndefined()
    expect(projectForPath('C:\\x', [{ id: 'broken' } as unknown as Project])).toBeUndefined()
    expect(projectForPath('C:\\x', undefined as unknown as Project[])).toBeUndefined()
    expect(projectForPath('C:\\x', 'nope' as unknown as Project[])).toBeUndefined()
  })
  it('agrees with sessionLogic.normPath on which spellings are the same path', () => {
    const spellings = [
      'C:\\Users\\chris\\income-kit',
      'c:/users/CHRIS/income-kit/',
      'C:/Users\\chris/income-kit\\'
    ]
    for (const a of spellings) {
      for (const b of spellings) {
        expect(normPath(a)).toBe(normPath(b))
        expect(projectForPath(a, [proj({ id: 'k', path: b })])?.id).toBe('k')
      }
    }
    expect(normPath('C:\\Users\\chris\\income-kit-old')).not.toBe(normPath(spellings[0]))
    expect(
      projectForPath('C:\\Users\\chris\\income-kit-old', [proj({ id: 'k', path: spellings[0] })])
    ).toBeUndefined()
  })
  it('matches from a drive root or a UNC project path', () => {
    expect(projectForPath('C:\\Users\\x', [proj({ id: 'root', path: 'C:\\' })])?.id).toBe('root')
    expect(projectForPath('\\\\srv\\share\\p\\x', [proj({ id: 'unc', path: '//srv/share/p' })])?.id).toBe(
      'unc'
    )
  })
})

