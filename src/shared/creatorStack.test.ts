/** Every seed entry present on disk, no registered projects. */
const fullStack = (): CreatorStack =>
  mergeSeed(
    emptyStack(NOW),
    seedEntries(HOME, () => true, [], NOW, winJoin),
    NOW
  )

const byId = (stack: CreatorStack, id: string): CreatorStackEntry => {
  const e = stack.entries.find((x) => x.id === id)
  if (!e) throw new Error(`no entry ${id}`)
  return e
}

